assert.equal(m.holding({...b, enabled: true, mismatch: true}, false), false)
assert.match(m.explanation({...b, enabled: true, percentage: 100}, false), /not actively drain/)
assert.match(m.explanation({...b, mode: 'full'}, false), /15 seconds/)
assert.equal(m.status({...b, state: 1, rate: 0}, false), 'Charging to full')
assert.equal(m.duration(0), '—')
assert.equal(m.duration(3660), '1h 1m')
assert.equal(m.percent(null), '—')
assert.equal(m.limitLabel({...b, end: null}), 'Protect battery')
assert.match(m.explanation({...b, supported: false}, false), /not available/)
assert.equal(m.protectionAction({...b, enabled: true}), 'off')
assert.equal(m.protectionAction({...b, enabled: false}), 'protect')
assert.match(m.explanation({...b, mode: 'off'}, false), /until you turn the limit on again/)
assert.equal(m.fullChargeActive({...b, mode: 'full', enabled: false}), true)
assert.equal(m.fullChargeAction({...b, mode: 'full', enabled: false}), 'protect')
assert.equal(m.fullChargeAction({...b, mode: 'protect', enabled: true}), 'full')
assert.equal(m.fullChargeActive({...b, mode: 'off', enabled: false}), false)
assert.equal(m.fullChargeActive({...b, mode: 'full', enabled: true}), false)
console.log('22 battery presentation regression checks passed')
